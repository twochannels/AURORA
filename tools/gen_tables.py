"""The AURORA voice's tables, computed here and written as numbers (the chip has no FPU: docs/RULES.md).
   tools/gen_tables.py  ->  firmware/gen/aurora_tables.h   (committed; tests/run_tests.sh checks it is current)"""
import math
from pathlib import Path

FS = 44100.0
CTL = 32                          # frames per control tick
TICK_S = CTL / FS                 # 0.7256 ms
out = []
w = out.append


def table(name, ctype, vals, per=8, fmt="{}", hot=False):   # hot: in RAM (.data), not the XIP flash: read every frame
    w(f"static {'' if hot else 'const '}{ctype} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), per):
        w("    " + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",")
    w("};")


w("/* SPDX-License-Identifier: GPL-3.0-only */")
w("/* Generated by tools/gen_tables.py: do not edit. */")
w("#pragma once")
w("#include <stdint.h>")
w(f"#define CTL {CTL}u                      /* frames per control tick ({TICK_S * 1000:.4f} ms) */")

# a sine cycle, 1024 points, Q15
table("SINE", "int16_t", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)])

# phase increment per frame of MIDI 120 + k / 16 (k = 0..191, the top octave): lower octaves shift right
table("PITCH16", "uint32_t", [round(440 * 2 ** ((120 + k / 16 - 69) / 12) * 2 ** 32 / FS) for k in range(192)], 6, "{}u")

# the SVF's g = tan(pi f / fs), Q12, for a cutoff at MIDI note 0..135 (8.2 Hz .. ~20 kHz, capped at 19 kHz)
def g_of(note):
    f = min(440 * 2 ** ((note - 69) / 12), 19000.0)
    return round(4096 * math.tan(math.pi * f / FS))
table("SVF_G", "int32_t", [g_of(n) for n in range(137)], 8)

# resonance knob 0..127 -> the SVF's damping k (Q12, k = 1/Q): the peak in dB is -6 + 16 (1 - e^(-r/1.8)) for r = knob/12.7,
# measured against the CS-80 V (chart 2 -> +5.7 dB, 8.5 -> +8.9 dB); 0 is Q 0.5 (k 2.0), 127 about +10 dB
table("SVF_KT", "uint16_t", [round(4096 / 10 ** ((-6 + 16 * (1 - math.exp(-(i / 12.7) / 1.8))) / 20)) for i in range(128)], 8)

# tanh(x / 32768) * 32767 for x = 0, 256, .. 65536 (257 points): the soft clip
table("TANH_Q15", "int16_t", [round(32767 * math.tanh(i * 256 / 32768)) for i in range(257)])

# envelope times: knob 0..127 -> 1 ms .. 12 s, exponential
def env_time(i):
    return 0.001 * (12000 ** (i / 127))
# attack: the fraction of the whole travel per tick, Q16 (linear ramp); knob 0 = at once (65536)
att = [min(65535, round(65536 * TICK_S / env_time(i))) for i in range(128)]
att[0] = 65535
table("ATT_Q16", "uint16_t", att, 8)
# decay / release: the fraction of the remaining distance per tick, Q16, for an exponential whose 99 % point
# (4.6 time constants) is the knob's time; capped at 1/2 (the Q15 products): knob 0 = at once
dec = [min(32768, round(65536 * (1 - math.exp(-TICK_S * 4.6 / env_time(i))))) for i in range(128)]
dec[0] = 32768
table("DEC_Q16", "uint16_t", dec, 8)

# LFO rate: knob 0..127 -> 0.1 .. 40 Hz exponential, as a phase increment per tick (2^32 a cycle)
table("LFO_INC", "uint32_t", [round(0.1 * (400 ** (i / 127)) * TICK_S * 2 ** 32) for i in range(128)], 6, "{}u")

# the ring modulator's rate: knob 0..127 -> 0.5 Hz .. 2 kHz exponential, as a phase increment per frame
table("RM_INC", "uint32_t", [round(0.5 * (4000 ** (i / 127)) * 2 ** 32 / FS) for i in range(128)], 6, "{}u")
# the delay's time: knob 0..127 -> 10 ms .. 1.1 s exponential, in frames
table("DLY_TIME", "uint16_t", [round(FS * 0.01 * (110 ** (i / 127))) for i in range(128)], 8)
# the reverb's feedback for a 2000-frame line: SIZE 0..127 -> a decay (T60) of 0.5 .. 25 s, Q15
# the phaser's allpass coefficient for a sweep 100 Hz .. 5 kHz (exponential over 128): p = (1 - tan(pi f / fs)) / (1 + tan)
table("PH_A", "int16_t", [round(32767 * (1 - math.tan(math.pi * 100 * (50 ** (i / 127)) / FS)) / (1 + math.tan(math.pi * 100 * (50 ** (i / 127)) / FS))) for i in range(128)], 8)

# the shimmer's heads run ahead of the write by (2^(s/12) - 1) frames a frame for an interval of s semitones, in 1/256 frame
table("SHIFT_INC", "uint16_t", [round(256 * (2 ** (i / 12) - 1)) for i in range(25)], 8)

# the ribbon (the SELECT encoder): cents a detent for RANGE 0..127 (5 .. 200), and the spring's return time for RETURN 1..127 (50 ms .. 5 s)
table("RIB_CENTS", "uint8_t", [round(5 * (40 ** (i / 127))) for i in range(128)], 16)
table("RIB_MS", "uint16_t", [round(50 * (100 ** (i / 127))) for i in range(128)], 8)

# the keys' velocity map (sense.c, fixed point): log2(x) in 1/256 for x = 0..1023 (0 -> 0), and 2^(-f/256) in Q15
table("LOG2_Q8", "uint16_t", [0] + [round(256 * math.log2(x)) for x in range(1, 1024)], 16)
table("EXP2N_Q15", "uint16_t", [round(32768 * 2 ** (-f / 256)) for f in range(256)], 8)

# the plate's decay, applied twice a round of 14930 frames for SIZE 0..127 -> RT60 0.5 .. 25 s
table("PLATE_D", "uint16_t", [round(32768 * math.exp(-6.908 * 7465 / (0.5 * (50 ** (i / 127)) * FS))) for i in range(128)], 8)

Path(__file__).resolve().parents[1].joinpath("firmware/gen/aurora_tables.h").write_text("\n".join(out) + "\n")
print("firmware/gen/aurora_tables.h written")
